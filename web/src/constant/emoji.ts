// Twemoji 对普通 emoji 去除 variation selector，ZWJ 序列则保留。
export function getTwemojiUrl(emoji: Emoji): string {
  const value = emoji.char.includes('\u200d') ? emoji.char : emoji.char.replace(/\ufe0f/g, '');
  const code = Array.from(value, (char) => char.codePointAt(0)!.toString(16)).join('-');
  return `https://cdn.jsdelivr.net/gh/jdecked/twemoji@17.0.3/assets/svg/${code}.svg`;
}
